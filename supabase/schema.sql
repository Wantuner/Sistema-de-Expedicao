create table if not exists public.filiais (
  id uuid primary key default gen_random_uuid(),
  nome text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.perfis (
  id uuid primary key references auth.users (id) on delete cascade,
  filial_id uuid not null references public.filiais (id) on delete restrict,
  created_at timestamptz not null default now()
);

create or replace function public.minha_filial_id()
returns uuid
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select filial_id
  from public.perfis
  where id = (select auth.uid())
$$;

create table if not exists public.clientes (
  id bigint generated by default as identity primary key,
  nome text not null,
  filial_id uuid references public.filiais (id) on delete restrict,
  created_at timestamptz not null default now()
);

create table if not exists public.transportadoras (
  id bigint generated by default as identity primary key,
  nome text not null,
  filial_id uuid references public.filiais (id) on delete restrict,
  created_at timestamptz not null default now()
);

create table if not exists public.motoristas (
  id bigint generated by default as identity primary key,
  nome text not null,
  filial_id uuid references public.filiais (id) on delete restrict,
  created_at timestamptz not null default now()
);

create table if not exists public.notas (
  id bigint generated by default as identity primary key,
  cliente text not null,
  transportadora text not null,
  nf text not null,
  pedido text not null,
  volumes integer not null check (volumes > 0),
  valor numeric(12, 2) not null check (valor >= 0),
  endereco text,
  caixa jsonb not null default '[]'::jsonb,
  expedido boolean not null default false,
  filial_id uuid references public.filiais (id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

